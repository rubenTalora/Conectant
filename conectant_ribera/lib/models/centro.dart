class Centro {
  final String id;
  final String name;
  final String address;
  final double lat;
  final double lng;
  final String associationId;
  final String description;

  Centro({
    required this.id,
    required this.name,
    required this.address,
    required this.lat,
    required this.lng,
    required this.associationId,
    required this.description,
  });
}
